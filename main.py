import cv2
from ultralytics import YOLO

# 1. Загружаем предобученную модель YOLO
# yolov8n.pt — это самая быстрая и легкая версия (nano).
# При первом запуске она автоматически скачается из интернета.
model = YOLO("yolov8n.pt")

# 2. Указываем URL вашего видеопотока
video_url = "http://192.168.96.77:8080/video"

# 3. Открываем видеопоток через OpenCV
cap = cv2.VideoCapture(video_url)

# Проверяем успешность подключения
if not cap.isOpened():
    print(f"❌ Ошибка: Не удалось открыть видеопоток по адресу {video_url}")
    print("Возможные причины:")
    print("  • Устройство (телефон/камера) выключено или не в той же сети Wi-Fi.")
    print("  • Приложение (например, DroidCam, IP Webcam) не запущено.")
    print("  • Брандмауэр Windows/Linux блокирует порт 8080.")
    exit()

print("✅ Успешное подключение к видеопотоку. Нажмите 'q' для выхода.")

# 4. Основной цикл обработки кадров
while True:
    ret, frame = cap.read()

    # Если кадр не получен (например, обрыв связи), прерываем цикл
    if not ret:
        print("⚠️ Не удалось получить кадр. Проверьте соединение.")
        break

    # 5. Передаем кадр в модель YOLO для инференса
    # verbose=False отключает лишний вывод текста в консоль для каждого кадра
    results = model(frame, verbose=False)

    # 6. Отрисовываем результаты (bounding boxes, классы, уверенность) на кадре
    # Метод .plot() автоматически возвращает кадр с нанесенной разметкой
    annotated_frame = results[0].plot()

    # 7. Отображаем обработанный кадр в окне
    cv2.imshow("YOLO Object Detection", annotated_frame)

    # 8. Обработка нажатия клавиш: выход из цикла по нажатию 'q'
    if cv2.waitKey(1) & 0xFF == ord('q'):
        break

# 9. Корректное освобождение ресурсов при завершении
cap.release()
cv2.destroyAllWindows()
